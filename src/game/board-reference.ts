/** Custom profiles are described from their current identities, never by a familiar board name. */
export function boardIntroduction(board: Board): BoardIntroduction {
  const known = board.tag === 'custom' ? undefined : BOARD_INTRODUCTIONS[board.id];
  if (known) return known;
  const entries = ROLE_IDS.filter(role => (board.roles[role] ?? 0) > 0);
  const total = entries.reduce((sum, role) => sum + (board.roles[role] ?? 0), 0);
  const names = entries.map(role => `${ROLES[role].name} ×${board.roles[role]}`).join('、');
  return {
    overview: `这是一套按当前身份配置的${total ? ` ${total} 人` : ''}自定义阵容，玩法由实际角色和本桌约定共同决定。`,
    highlights: [names ? `当前配置：${names}。` : '尚未设置身份，请先补齐阵容。', '同名方案不代表采用某个固定板子的技能或规则版本。'],
    hostChecks: ['核对完整人数、实际身份与每张特殊牌的版本和触发条件。', '确认警长、胜负、夜间顺序和特殊联动，再按本桌规则开始。'],
  };
}
